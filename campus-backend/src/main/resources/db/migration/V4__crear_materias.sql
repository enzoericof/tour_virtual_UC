CREATE TABLE materias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE materias_carreras (
    materia_id BIGINT NOT NULL,
    carrera SMALLINT NOT NULL,

    CONSTRAINT pk_materias_carreras
        PRIMARY KEY (materia_id, carrera),

    CONSTRAINT fk_materias_carreras_materia
        FOREIGN KEY (materia_id)
        REFERENCES materias(id),

    CONSTRAINT chk_materias_carreras_carrera
        CHECK (carrera IN (1, 2))
);

CREATE INDEX idx_materias_carreras_carrera
    ON materias_carreras(carrera, materia_id);