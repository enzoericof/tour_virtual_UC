
CREATE TABLE archivos_trabajo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trabajo_id BIGINT NOT NULL,
    tipo SMALLINT NOT NULL,

    nombre_archivo VARCHAR(255) NOT NULL,
    ruta_archivo VARCHAR(500) NOT NULL,

    orden INTEGER NOT NULL DEFAULT 0,
    fecha_subida TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_archivos_trabajo_trabajo
        FOREIGN KEY (trabajo_id)
        REFERENCES trabajos(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_archivos_trabajo_tipo
        CHECK (tipo IN (1, 2)),

    CONSTRAINT chk_archivos_trabajo_orden
        CHECK (orden >= 0)
);

CREATE INDEX idx_archivos_trabajo_trabajo_id
    ON archivos_trabajo(trabajo_id);

CREATE UNIQUE INDEX uq_archivos_un_video_por_trabajo
    ON archivos_trabajo(trabajo_id)
    WHERE tipo = 2;
