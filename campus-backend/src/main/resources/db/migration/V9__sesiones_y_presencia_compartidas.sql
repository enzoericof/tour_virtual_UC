CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL UNIQUE,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE INDEX SPRING_SESSION_IX_EXPIRY ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX_PRINCIPAL ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);

CREATE TABLE campus_presence (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    session_id CHAR(36) NOT NULL REFERENCES SPRING_SESSION(SESSION_ID) ON DELETE CASCADE ON UPDATE CASCADE,
    pose JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX campus_presence_updated ON campus_presence(updated_at);
